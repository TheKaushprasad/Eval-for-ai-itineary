"use client";

import Link from "next/link";
import { useState } from "react";
import ItineraryView from "@/components/ItineraryView";
import ProgressSteps, { type StepState } from "@/components/ProgressSteps";
import TripForm from "@/components/TripForm";
import type { PlannerMode } from "@/lib/access";
import type { Example } from "@/lib/examples";
import type { ItineraryResult, ProgressStep, TripRequest } from "@/lib/schema";
import { readEvents } from "@/lib/sse";

export default function Planner({ mode, examples }: { mode: PlannerMode; examples: Example[] }) {
  const [busy, setBusy] = useState(false);
  const [steps, setSteps] = useState<Partial<Record<ProgressStep, StepState>>>({});
  const [result, setResult] = useState<ItineraryResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [code, setCode] = useState("");

  async function generate(req: TripRequest) {
    setBusy(true);
    setError(null);
    setResult(null);
    setSteps({});
    try {
      const res = await fetch("/api/itinerary", {
        method: "POST",
        headers: { "Content-Type": "application/json", ...(code && { "x-access-code": code }) },
        body: JSON.stringify(req),
      });
      if (!res.ok || !res.body) {
        const body = await res.json().catch(() => ({}));
        throw new Error(body.error || `Request failed (${res.status})`);
      }
      for await (const ev of readEvents(res)) {
        if (ev.type === "progress") setSteps((s) => ({ ...s, [ev.step]: { status: ev.status, detail: ev.detail } }));
        else if (ev.type === "result") setResult(ev.data);
        else if (ev.type === "error") throw new Error(ev.message);
      }
    } catch (e) {
      setError(e instanceof Error ? e.message : "Something went wrong");
    } finally {
      setBusy(false);
    }
  }

  if (result) {
    return (
      <main className="mx-auto w-full max-w-5xl px-4 py-10 sm:py-14">
        <ItineraryView result={result} onReset={() => setResult(null)} />
      </main>
    );
  }

  return (
    <main className="mx-auto w-full max-w-5xl px-4 py-10 sm:py-14">
      <div className="mb-8">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <p className="text-sm font-semibold uppercase tracking-widest text-teal-700">AI travel planner</p>
          <Link href="/evals" className="text-sm font-medium text-teal-800 hover:underline">
            How it&apos;s evaluated →
          </Link>
        </div>
        <h1 className="mt-2 text-3xl font-bold tracking-tight text-stone-900 sm:text-4xl">Your whole trip, planned in one go.</h1>
        <p className="mt-3 max-w-2xl text-stone-600">
          Tell us where, when and how you like to travel. We check the weather, flights, places and prices, then build a day-by-day
          plan that fits your budget.
        </p>
      </div>

      {examples.length > 0 && (
        <section className="mb-10">
          <h2 className="mb-3 font-semibold text-stone-900">Example trips</h2>
          <ul className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {examples.map((ex) => (
              <li key={ex.id}>
                <button
                  onClick={() => setResult(ex.result)}
                  className="h-full w-full rounded-2xl border border-stone-200 bg-white p-5 text-left transition hover:border-teal-600 hover:shadow-sm"
                >
                  <p className="font-medium text-stone-900">{ex.title}</p>
                  <p className="mt-1 text-sm text-stone-600">{ex.blurb}</p>
                  <p className="mt-3 text-xs text-stone-400">Generated by the planner · {ex.source}</p>
                </button>
              </li>
            ))}
          </ul>
        </section>
      )}

      {mode === "examples" ? (
        <p className="rounded-2xl border border-dashed border-stone-300 p-6 text-sm text-stone-600">
          Live planning is switched off in this public demo to keep API costs at zero. The example trips above are real output from the
          planner, and the <Link href="/evals" className="text-teal-800 underline">evaluation dashboard</Link> shows how each version
          was measured.
        </p>
      ) : (
        <div className="grid gap-8 lg:grid-cols-[1fr_320px]">
          <TripForm onSubmit={generate} busy={busy} />
          <aside className="flex flex-col gap-4 lg:sticky lg:top-8 lg:self-start">
            {mode === "code" && (
              <label className="rounded-2xl border border-stone-200 bg-white p-5 text-sm">
                <span className="font-medium text-stone-900">Access code</span>
                <span className="mt-1 block text-stone-500">Live planning uses paid AI calls, so it needs the code from my CV.</span>
                <input
                  type="password"
                  value={code}
                  onChange={(e) => setCode(e.target.value)}
                  autoComplete="off"
                  className="mt-2 w-full rounded-lg border border-stone-300 px-3 py-2"
                />
              </label>
            )}
            {busy || Object.keys(steps).length ? (
              <ProgressSteps state={steps} />
            ) : (
              <div className="rounded-2xl border border-dashed border-stone-300 p-6 text-sm text-stone-500">
                Pre-filled with an example: 5 relaxed vegetarian days in Goa from Bangalore for two adults. Change anything, then
                generate.
              </div>
            )}
            {error && <p className="rounded-xl border border-red-200 bg-red-50 p-4 text-sm text-red-800">{error}</p>}
          </aside>
        </div>
      )}
    </main>
  );
}
